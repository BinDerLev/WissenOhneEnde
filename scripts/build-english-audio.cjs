#!/usr/bin/env node
// Export the finite English corpus and generate static clips with local Kokoro.
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const vm = require("node:vm");
const crypto = require("node:crypto");
const { spawnSync } = require("node:child_process");

const root = path.resolve(__dirname, "..");
const app = path.join(root, "Lern-App");
const context = vm.createContext({});
for (const file of ["english.js", "english-speech.js"]) {
  new vm.Script(fs.readFileSync(path.join(app, file), "utf8"), { filename: file }).runInContext(context);
}
const texts = vm.runInContext("collectEnglishAudioTexts()", context);
const id = process.env.ENGLISH_AUDIO_VOICE || "af_heart";
const voices = { af_heart: ["Heart", "en-US"], bf_emma: ["Emma", "en-GB"] };
if (!voices[id]) throw new Error("Supported female English voices: af_heart, bf_emma.");
const speed = Number(process.env.ENGLISH_AUDIO_SPEED || "0.95");
if (!Number.isFinite(speed) || speed < 0.7 || speed > 1.2) throw new Error("Use a speaking speed between 0.7 and 1.2.");
const signature = `kokoro-v1.0-fp32:${id}:${speed}:mp3-64k:v1`;
const voice = {
  name: voices[id][0], id, language: voices[id][1], engine: "Kokoro 82M", speed, sampleRate: 24000, signature,
  modelSha256: "beb0d1848dee9a49da392cc3df26958d46cfa35d321edf434f52949153f0df3a",
  voicesSha256: "bca610b8308e8d99f32e6fe4197e7ec01679264efed0cac9140fe9c29f1fbf7d"
};
const hash = text => crypto.createHash("sha256").update(`${signature}:${text}`).digest("hex").slice(0, 24);
const manifest = Object.fromEntries(texts.map(text => [text, `audio/english/${hash(text)}.mp3`]));
const catalogue = { voice, texts, manifest };
if (process.argv.includes("--list")) {
  process.stdout.write(JSON.stringify(catalogue, null, 2));
  process.exit(0);
}
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "lernlabor-english-catalogue-"));
try {
  const cataloguePath = path.join(temporary, "catalogue.json");
  fs.writeFileSync(cataloguePath, JSON.stringify(catalogue));
  const python = process.env.ENGLISH_AUDIO_PYTHON || "python3";
  const result = spawnSync(python, [path.join(__dirname, "build_english_audio.py"), "--catalogue", cataloguePath, "--app", app,
    ...(process.env.ENGLISH_AUDIO_MODEL_DIR ? ["--model-dir", process.env.ENGLISH_AUDIO_MODEL_DIR] : []),
    ...(process.env.ENGLISH_AUDIO_WORKERS ? ["--workers", process.env.ENGLISH_AUDIO_WORKERS] : [])
  ], { stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exitCode = result.status || 1;
  else {
    // Publish only after the complete chosen voice is available.
    const source = `// Generated by scripts/build-english-audio.cjs.\nconst englishAudioVoice = ${JSON.stringify(voice)};\nconst englishAudioManifest = ${JSON.stringify(manifest, null, 2)};\n`;
    const pending = path.join(app, "english-audio-manifest.js.pending");
    fs.writeFileSync(pending, source);
    fs.renameSync(pending, path.join(app, "english-audio-manifest.js"));
    const bytes = Object.values(manifest).reduce((sum, file) => sum + fs.statSync(path.join(app, file)).size, 0);
    console.log(`Complete: ${texts.length} clips, ${(bytes / 1024 / 1024).toFixed(1)} MiB, ${voice.name} (${voice.language}).`);
  }
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
