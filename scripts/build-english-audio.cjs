#!/usr/bin/env node
// Export the finite English corpus and generate static clips with local Kokoro.
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const vm = require("node:vm");
const crypto = require("node:crypto");
const { spawnSync } = require("node:child_process");

const root = path.resolve(__dirname, "..");
const app = path.join(root, "Lern-App");
const context = vm.createContext({});
for (const file of ["english.js", "english-speech.js"]) {
  new vm.Script(fs.readFileSync(path.join(app, file), "utf8"), { filename: file }).runInContext(context);
}
const texts = vm.runInContext("collectEnglishAudioTexts()", context);
const id = process.env.ENGLISH_AUDIO_VOICE || "bf_emma";
const voices = { af_heart: ["Heart", "en-US"], bf_emma: ["Emma", "en-GB"] };
if (!voices[id]) throw new Error("Supported female English voices: af_heart, bf_emma.");
const speed = Number(process.env.ENGLISH_AUDIO_SPEED || "0.95");
if (!Number.isFinite(speed) || speed < 0.7 || speed > 1.2) throw new Error("Use a speaking speed between 0.7 and 1.2.");
const signature = `kokoro-v1.0-fp32:${id}:${speed}:mp3-64k:v1`;
const voice = {
  name: voices[id][0], id, language: voices[id][1], engine: "Kokoro 82M", speed, sampleRate: 24000, signature,
  modelSha256: "beb0d1848dee9a49da392cc3df26958d46cfa35d321edf434f52949153f0df3a",
  voicesSha256: "bca610b8308e8d99f32e6fe4197e7ec01679264efed0cac9140fe9c29f1fbf7d"
};
const hash = text => crypto.createHash("sha256").update(`${signature}:${text}`).digest("hex").slice(0, 24);
const manifest = Object.fromEntries(texts.map(text => [text, `audio/english/${hash(text)}.mp3`]));
const regenerateParentheses = process.argv.includes("--regenerate-parentheses");
const generationTexts = regenerateParentheses ? texts.filter(text => /[()]/.test(text)) : texts;
const generationManifest = Object.fromEntries(generationTexts.map(text => [text, manifest[text]]));
const catalogue = { voice, texts: generationTexts, manifest: generationManifest };
if (process.argv.includes("--list")) {
  process.stdout.write(JSON.stringify(catalogue, null, 2));
  process.exit(0);
}
let previousManifest = {};
if (process.argv.includes("--replace") && fs.existsSync(path.join(app, "english-audio-manifest.js"))) {
  const previousContext = vm.createContext({});
  new vm.Script(fs.readFileSync(path.join(app, "english-audio-manifest.js"), "utf8")).runInContext(previousContext);
  previousManifest = vm.runInContext("englishAudioManifest", previousContext);
}
if (process.argv.includes("--prune")) {
  for (const file of Object.values(manifest)) {
    const absolute = path.join(app, file);
    if (!fs.existsSync(absolute) || fs.statSync(absolute).size < 500) {
      throw new Error(`Cannot prune with an incomplete retained recording: ${file}`);
    }
  }
  const source = `// Generated by scripts/build-english-audio.cjs.\nconst englishAudioVoice = ${JSON.stringify(voice)};\nconst englishAudioManifest = ${JSON.stringify(manifest, null, 2)};\n`;
  const pending = path.join(app, "english-audio-manifest.js.pending");
  fs.writeFileSync(pending, source);
  fs.renameSync(pending, path.join(app, "english-audio-manifest.js"));
  const currentFiles = new Set(Object.values(manifest));
  let removed = 0;
  for (const file of new Set(Object.values(previousManifest))) {
    if (!currentFiles.has(file) && /^audio\/english\/[a-f0-9]{24}\.mp3$/.test(file) && fs.existsSync(path.join(app, file))) {
      fs.unlinkSync(path.join(app, file));
      removed++;
    }
  }
  console.log(`Pruned ${removed} unused recordings; ${texts.length} retained clips remain.`);
  process.exit(0);
}
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "lernlabor-english-catalogue-"));
try {
  const cataloguePath = path.join(temporary, "catalogue.json");
  fs.writeFileSync(cataloguePath, JSON.stringify(catalogue));
  const cachedPython = path.join(root, ".cache", "english-audio", "bin", "python");
  const python = process.env.ENGLISH_AUDIO_PYTHON || (fs.existsSync(cachedPython) ? cachedPython : "python3");
  const cachedModelDir = path.join(root, ".cache", "kokoro");
  const modelDir = process.env.ENGLISH_AUDIO_MODEL_DIR || (fs.existsSync(path.join(cachedModelDir, "kokoro-v1.0.onnx")) ? cachedModelDir : null);
  const result = spawnSync(python, [path.join(__dirname, "build_english_audio.py"), "--catalogue", cataloguePath, "--app", app,
    ...(modelDir ? ["--model-dir", modelDir] : []),
    ...(regenerateParentheses ? ["--force"] : []),
    ...(process.env.ENGLISH_AUDIO_WORKERS ? ["--workers", process.env.ENGLISH_AUDIO_WORKERS] : [])
  ], { stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exitCode = result.status || 1;
  else if (regenerateParentheses) {
    let bytes = 0;
    for (const file of Object.values(generationManifest)) {
      const size = fs.statSync(path.join(app, file)).size;
      if (size < 500) throw new Error(`Incomplete regenerated recording: ${file}`);
      bytes += size;
    }
    console.log(`Regenerated ${generationTexts.length} parenthesized clips (${(bytes / 1024 / 1024).toFixed(1)} MiB). Manifest keys unchanged.`);
  }
  else {
    // Publish only after the complete chosen voice is available.
    const bytes = Object.values(manifest).reduce((sum, file) => {
      const size = fs.statSync(path.join(app, file)).size;
      if (size < 500) throw new Error(`Incomplete English recording: ${file}`);
      return sum + size;
    }, 0);
    const source = `// Generated by scripts/build-english-audio.cjs.\nconst englishAudioVoice = ${JSON.stringify(voice)};\nconst englishAudioManifest = ${JSON.stringify(manifest, null, 2)};\n`;
    const pending = path.join(app, "english-audio-manifest.js.pending");
    fs.writeFileSync(pending, source);
    fs.renameSync(pending, path.join(app, "english-audio-manifest.js"));
    const currentFiles = new Set(Object.values(manifest));
    let removed = 0;
    for (const file of new Set(Object.values(previousManifest))) {
      if (!currentFiles.has(file) && /^audio\/english\/[a-f0-9]{24}\.mp3$/.test(file) && fs.existsSync(path.join(app, file))) {
        fs.unlinkSync(path.join(app, file));
        removed++;
      }
    }
    if (removed) console.log(`Replaced ${removed} superseded recordings.`);
    console.log(`Complete: ${texts.length} clips, ${(bytes / 1024 / 1024).toFixed(1)} MiB, ${voice.name} (${voice.language}).`);
  }
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
